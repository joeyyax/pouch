// Writes lib/observations/registry.generated.ts from the files in lib/observations/.
// A file is an observation file unless its name starts with "_" or ends in ".generated.ts".
// `--check` exits 1 when the committed file doesn't match the folder.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const folder = path.join(root, "lib/observations");
export const registryPath = path.join(folder, "registry.generated.ts");

export function observationFiles(names = readdirSync(folder)) {
  return names
    .filter((name) => name.endsWith(".ts") && !name.startsWith("_") && !name.endsWith(".generated.ts") && !name.endsWith(".d.ts"))
    .sort();
}

export function renderRegistry(files = observationFiles()) {
  const modules = files.map((file, index) => ({ name: `m${index}`, specifier: `./${file.replace(/\.ts$/, "")}` }));
  const lines = [
    "// Generated by scripts/gen-observations.mjs from the files in this folder. Don't edit.",
    'import { isObservation, type ExportedObservations, type Observation } from "./_types";',
    ...modules.map((module) => `import * as ${module.name} from "${module.specifier}";`),
    "",
    `const MODULES = [${modules.map((module) => module.name).join(", ")}] as const;`,
    "",
    "/** Every observation any file in this folder exports. */",
    "export const OBSERVATIONS: readonly Observation[] = MODULES.flatMap((module) => Object.values(module).filter(isObservation));",
    "",
    `export type RegisteredObservation = ${modules.length === 0 ? "never" : modules.map((module) => `ExportedObservations<typeof ${module.name}>`).join(" | ")};`,
    "",
    'export type ObservationKey = RegisteredObservation["key"];',
    "",
  ];
  return lines.join("\n");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const next = renderRegistry();
  let current = "";
  try {
    current = readFileSync(registryPath, "utf8");
  } catch {
    current = "";
  }
  if (process.argv.includes("--check")) {
    if (current !== next) {
      console.error("lib/observations/registry.generated.ts is out of date. Run `node scripts/gen-observations.mjs`.");
      process.exit(1);
    }
  } else if (current !== next) {
    writeFileSync(registryPath, next);
  }
}
